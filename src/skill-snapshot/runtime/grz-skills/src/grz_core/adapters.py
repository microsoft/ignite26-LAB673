"""Shared adapter boundaries; live operations must enforce approvals in the calling service."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol

from grz_core.contracts import SourceIdentity


class BuildStore(Protocol):
    def inspect(self, source: SourceIdentity) -> dict[str, Any]: ...
    def export_snapshot(self, source: SourceIdentity, destination: Path) -> Path: ...
    def create_generation_index(self, index: str, dimension: int) -> None: ...
    def upload_batch(self, index: str, documents: list[dict[str, Any]]) -> list[dict[str, Any]]: ...
    def readback(self, index: str) -> list[dict[str, Any]]: ...
    def resolve_alias(self, alias: str) -> str | None: ...
    def switch_alias(self, alias: str, expected: str | None, target: str) -> None: ...
    def generation_index_name(self, generation_id: str) -> str: ...
    def verify(self, index: str, expected: list[dict[str, Any]]) -> None: ...


class ReadStore(Protocol):
    def documents(self, physical_index: str, kind: str, generation_id: str) -> list[dict[str, Any]]: ...
